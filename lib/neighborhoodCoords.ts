export function getNeighborhoodCoords(neighborhood?: string, city?: string): [number, number] | null {
  const norm = (str?: string) => 
    str ? str.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim() : '';

  const normN = norm(neighborhood);
  const normC = norm(city);

  // Check exact neighborhood match
  if (normN && PB_NEIGHBORHOOD_COORDS[normN]) {
    return PB_NEIGHBORHOOD_COORDS[normN];
  }

  // Check city match
  if (normC && PB_NEIGHBORHOOD_COORDS[normC]) {
    return PB_NEIGHBORHOOD_COORDS[normC];
  }

  // Partial match in keys
  for (const [key, coords] of Object.entries(PB_NEIGHBORHOOD_COORDS)) {
    const normKey = norm(key);
    if (normN && (normKey.includes(normN) || normN.includes(normKey))) {
      return coords;
    }
  }

  return null;
}
